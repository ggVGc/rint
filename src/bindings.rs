//! Discover native function references using the interpreter's AST and resolver.
use crate::ast::Type;

/// Collect external function paths in first-use order, including alias expansion.
/// Unknown qualified paths are treated as external functions. Rust validates the
/// generated references when the host application is compiled.
pub fn discover(src: &str) -> Result<Vec<String>, String> {
    let items = crate::parser::parse_program(crate::lexer::tokenize(src)?)?;
    let (_, paths) = crate::resolve::resolve_with_native(items, vec![], true)?;
    Ok(paths)
}

/// Low-level registration generation for source whose external roots have
/// already been vetted. Build scripts should use [`generate_for_dependencies`].
pub fn generate(src: &str) -> Result<String, String> {
    generate_paths(discover(src)?)
}

/// Generate bindings only for names supplied by the host's external Cargo
/// dependencies. References to the host crate or unknown modules are rejected;
/// they must eventually be resolved as interpreted application modules.
pub fn generate_for_dependencies(src: &str, dependencies: &[String]) -> Result<String, String> {
    let paths = discover(src)?;
    for path in &paths {
        let root = path.split("::").next().unwrap();
        if !dependencies.iter().any(|dependency| dependency == root) {
            return Err(format!(
                "cannot generate native binding for `{path}`: `{root}` is not an external dependency; application modules must be interpreted (module imports are not supported yet)"
            ));
        }
    }
    generate_paths(paths)
}

fn generate_paths(paths: Vec<String>) -> Result<String, String> {
    let mut output = String::from(
        "// Generated by rint; do not edit.\npub fn register_generated_bindings(engine: &mut ::rint::Engine) -> Result<(), String> {\n",
    );
    for path in paths {
        output.push_str(&format!("    engine.register_fn({path:?}, {path})?;\n"));
    }
    output.push_str("    Ok(())\n}\n");
    Ok(output)
}

pub(crate) fn rust_type(ty: &Type) -> Result<String, String> {
    match ty.name.as_str() {
        "&" if ty.args.len() == 1 => Ok(format!("&{}", rust_type(&ty.args[0])?)),
        "tuple" if ty.args.is_empty() => Ok("()".into()),
        "tuple" => Ok(format!(
            "({},)",
            ty.args
                .iter()
                .map(rust_type)
                .collect::<Result<Vec<_>, _>>()?
                .join(", ")
        )),
        name if name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            && name != "_"
            && !name.is_empty() =>
        {
            if ty.args.is_empty() {
                Ok(name.into())
            } else {
                Ok(format!(
                    "{name}<{}>",
                    ty.args
                        .iter()
                        .map(rust_type)
                        .collect::<Result<Vec<_>, _>>()?
                        .join(", ")
                ))
            }
        }
        _ => Err(format!("unsupported native generic type `{}`", ty.name)),
    }
}
